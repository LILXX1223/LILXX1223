import { test, expect } from '@playwright/test'

test('总览六个板块使用业务数据并在设置变更后刷新',async({page})=>{
  await page.goto('/')
  await page.getByPlaceholder('请输入账号').fill('group3')
  await page.getByPlaceholder('请输入密码').fill(process.env.E2E_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  const cards=page.locator('.overview-grid > section')
  await expect(cards).toHaveCount(6)
  for(const [index,title] of ['病区概况（今日）','本周排班','班次人力配置（今日）','人力充足性评估','护士能力结构','重点提示'].entries())
    await expect(cards.nth(index).locator('h2')).toContainText(title)
  const response=await page.request.get('/api/v1/overview/')
  const data=(await response.json()).data
  await expect(cards.nth(0).locator('.overview-metric').nth(0)).toContainText(String(data.beds))
  await expect(cards.nth(0).locator('.overview-metric').nth(1)).toContainText(String(data.patients))
  await expect(cards.nth(0)).toContainText('暂无可靠数据来源')
  await expect(cards.nth(1)).toContainText('正式版本 #'+data.publication.id)
  await expect(cards.nth(1)).toContainText('无阻断')
  const a=data.shifts.find(shift=>shift.code==='A')
  const aCard=cards.nth(2).locator('.shift-card').nth(0)
  await expect(aCard).toContainText('最低需求 '+a.need+' 人')
  await expect(aCard).toContainText(a.coverage+'%')
  await expect(cards.nth(2)).toContainText('夜下休')
  await expect(cards.nth(3)).toContainText('当前人数规则尚未由科室确认')
  for(const [width,height,path] of [[1920,1080,process.env.ICU_OVERVIEW_SHOT_1920],[1366,768,process.env.ICU_OVERVIEW_SHOT_1366]]){
    await page.setViewportSize({width,height})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    if(path)await page.screenshot({path,fullPage:true,animations:'disabled'})
  }
  await page.getByRole('link',{name:'系统设置',exact:true}).click()
  const config=page.locator('.bed-config')
  await config.getByRole('button',{name:'8床 ✓',exact:true}).click()
  await config.getByRole('button',{name:'保存床位设置',exact:true}).click()
  await page.getByRole('dialog',{name:'确认床位配置影响'}).getByRole('button',{name:'确认保存'}).click()
  await page.getByRole('link',{name:'总览',exact:true}).click()
  await expect(page.locator('.overview-grid')).toBeVisible()
  await expect(page.locator('.overview-grid').getByText('部分开放床位未设置显示')).toBeVisible()
  const refreshed=(await (await page.request.get('/api/v1/overview/')).json()).data
  expect(refreshed.beds).toBe(data.beds)
  expect(refreshed.patients).toBe(data.patients)
  await expect(page.locator('.overview-grid').getByText('1 张开放床位未在工作台配置为显示，仍计入开放床位。')).toBeVisible()
  await page.route('**/api/v1/overview/**',route=>route.fulfill({status:503,json:{error:{message:'合成测试：服务暂不可用'}}}))
  await page.getByRole('button',{name:'刷新数据',exact:true}).click()
  await expect(page.getByText(/以下为上次获取的数据，可能已过期/)).toBeVisible()
  await expect(page.locator('.overview-grid > section')).toHaveCount(6)
})
