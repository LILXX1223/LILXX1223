import { test, expect } from '@playwright/test'

test('时钟与时段排班撤销：预览、确认、刷新及正式快照保护',async({page},info)=>{
  await page.goto('/')
  await page.getByPlaceholder('请输入账号').fill('group3')
  await page.getByPlaceholder('请输入密码').fill(process.env.E2E_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  const clock=page.getByLabel('北京时间')
  await expect(clock).toHaveText(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/)
  const first=await clock.textContent()
  await expect.poll(()=>clock.textContent(),{timeout:5000}).not.toBe(first)
  await page.getByRole('link',{name:'排班管理',exact:true}).click()
  await expect(clock).toBeVisible()
  const response=await page.request.get('/api/v1/workspace/')
  expect(response.ok()).toBeTruthy()
  const before=(await response.json()).data
  const official=JSON.stringify(before.publications)
  const originalDraft=before.draft.entries.length
  await page.getByRole('button',{name:'撤销时段排班'}).click()
  const dialog=page.getByRole('dialog',{name:'撤销时段排班'})
  const tomorrow=new Date(before.today+'T12:00:00Z');tomorrow.setUTCDate(tomorrow.getUTCDate()+1)
  const day=tomorrow.toISOString().slice(0,10)
  await dialog.getByRole('button',{name:'自定义'}).click()
  await dialog.getByPlaceholder('开始日期').fill(day);await dialog.getByPlaceholder('开始日期').press('Enter')
  await dialog.getByPlaceholder('结束日期').fill(day);await dialog.getByPlaceholder('结束日期').press('Enter')
  await expect(dialog.getByText('需撤销班次',{exact:true})).toBeVisible()
  await expect.poll(async()=>{
    const cards=dialog.locator('.cancel-stats div')
    return Number((await cards.nth(2).locator('strong').innerText()).replace(/\D/g,''))
  }).toBeGreaterThan(0)
  await page.screenshot({path:info.outputPath('schedule-cancel.png'),animations:'disabled'})
  await page.setViewportSize({width:1366,height:768})
  await expect(dialog.getByRole('button',{name:'确认撤销'})).toBeVisible()
  await page.screenshot({path:info.outputPath('schedule-cancel-768.png'),animations:'disabled'})
  await dialog.getByPlaceholder('请填写撤销原因').fill('隔离测试：验证历史记录保护')
  await dialog.getByRole('button',{name:'确认撤销'}).click()
  await page.getByRole('dialog',{name:'二次确认'}).getByRole('button',{name:'确认撤销'}).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  const afterResponse=await page.request.get('/api/v1/workspace/')
  const after=(await afterResponse.json()).data
  expect(JSON.stringify(after.publications)).toBe(official)
  expect(after.draft.entries.length).toBeLessThan(originalDraft)
  await expect(clock).toBeVisible()
})
