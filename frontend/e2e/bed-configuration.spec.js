import { test, expect } from '@playwright/test'

test('床位配置保留患者、分离显示与开放并持久化自定义床号', async ({page}) => {
  await page.goto('/')
  await page.getByPlaceholder('请输入账号').fill('group3')
  await page.getByPlaceholder('请输入密码').fill(process.env.E2E_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'系统设置',exact:true}).click()
  const config=page.locator('.bed-config')
  await expect(config.getByText('本组床位设置')).toBeVisible()
  await expect(config.locator('.bed-config-chip')).toHaveCount(8)
  await expect(config).toContainText('已配置 8 床')
  const numbers=config.locator('.el-input-number input')
  await numbers.nth(0).fill('101');await numbers.nth(1).fill('3')
  await config.getByRole('button',{name:'生成编号',exact:true}).click()
  await expect(config.getByRole('button',{name:'101床 ✓'})).toBeVisible()
  await expect(config.getByRole('button',{name:'103床 ✓'})).toBeVisible()
  await config.getByRole('button',{name:'保存床位设置',exact:true}).click()
  let dialog=page.getByRole('dialog',{name:'确认床位配置影响'})
  await expect(dialog.getByRole('button',{name:'确认保存'})).toBeDisabled()
  await expect(dialog).toContainText('在床患者')
  await dialog.getByRole('button',{name:'取消'}).click()
  await numbers.nth(0).fill('1');await numbers.nth(1).fill('8')
  await config.getByRole('button',{name:'生成编号',exact:true}).click()
  await config.getByRole('button',{name:'取消全选',exact:true}).click()
  await expect(config.getByRole('button',{name:'8床',exact:true})).toHaveAttribute('aria-pressed','false')
  await config.getByRole('button',{name:'全选',exact:true}).click()
  await config.getByPlaceholder('自定义床号，如 101A').fill('101A')
  await config.getByRole('button',{name:'添加床号',exact:true}).click()
  const custom=config.locator('.bed-config-item').filter({has:page.getByRole('button',{name:'101A床 ✓'})})
  await expect(custom).toContainText('未开放')
  await custom.locator('.el-switch').click()
  await config.getByRole('button',{name:'8床 ✓',exact:true}).click()
  await config.getByRole('button',{name:'保存床位设置',exact:true}).click()
  dialog=page.getByRole('dialog',{name:'确认床位配置影响'})
  await expect(dialog).toContainText('新增 1 床')
  await dialog.getByRole('button',{name:'确认保存'}).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await expect(config.locator('.bed-config-chip')).toHaveCount(9)
  await expect(config.getByRole('button',{name:'8床',exact:true})).toHaveAttribute('aria-pressed','false')
  await expect(config.getByRole('button',{name:'101A床 ✓'})).toBeVisible()
  await expect(config).toContainText('实际开放 9 床')
  if(process.env.ICU_BED_CONFIG_SCREENSHOT)await page.screenshot({path:process.env.ICU_BED_CONFIG_SCREENSHOT,fullPage:true})
  await page.getByRole('link',{name:'床位分配',exact:true}).click()
  await expect(page.locator('.bed-card')).toHaveCount(8)
  await expect(page.locator('.bed-card').filter({hasText:'101A床'})).toBeVisible()
  await expect(page.locator('.bed-card').filter({hasText:'8床'})).toHaveCount(0)
  await expect(page.locator('.kpi').filter({hasText:'开放床位'})).toContainText('9')
  await expect(page.locator('.kpi').filter({hasText:'在床患者'})).toContainText('7')
  await expect(page.locator('.kpi').filter({hasText:'空床'})).toContainText('2')
  await expect(page.getByText('1 张开放床位未设置显示，仍计入开放及空床统计；请核对实际管理范围。')).toBeVisible()
})
