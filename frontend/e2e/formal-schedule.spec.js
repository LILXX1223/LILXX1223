import { test, expect } from '@playwright/test'

test('总览撤销未来正式班次，重新生成草稿后发布新版本',async({page})=>{
  test.setTimeout(90000)
  await page.goto('/')
  await page.getByPlaceholder('请输入账号').fill('group3')
  await page.getByPlaceholder('请输入密码').fill(process.env.E2E_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page.getByRole('link',{name:'排班管理',exact:true})).toBeVisible()
  const get=async path=>(await (await page.request.get('/api/v1/'+path)).json()).data
  const before=await get('workspace/'),week=before.today.slice(0,10)
  const tomorrow=new Date(week+'T12:00:00Z');tomorrow.setUTCDate(tomorrow.getUTCDate()+1)
  const day=tomorrow.toISOString().slice(0,10)
  test.skip(day>new Date(before.published_week.start_date+'T12:00:00Z').toISOString().slice(0,10) &&
    (new Date(day+'T12:00:00Z')-new Date(before.published_week.start_date+'T12:00:00Z'))/86400000>6,'本周无未来日期')
  const original=JSON.stringify(before.publications.find(p=>p.id===before.published_week.id).entries)
  await page.getByRole('button',{name:'撤销正式排班'}).click()
  const dialog=page.getByRole('dialog',{name:'撤销已发布正式排班'})
  await expect(dialog).toContainText('正式版本 #'+before.published_week.id)
  await dialog.getByText('撤销指定时段',{exact:true}).click()
  await dialog.getByPlaceholder('开始日期').fill(day);await dialog.getByPlaceholder('开始日期').press('Enter')
  await dialog.getByPlaceholder('结束日期').fill(day);await dialog.getByPlaceholder('结束日期').press('Enter')
  await dialog.getByPlaceholder('请填写撤销原因').fill('隔离测试：重新生成未来排班')
  await expect(dialog.getByRole('button',{name:'确认撤销',exact:true})).toBeEnabled({timeout:10000})
  await dialog.getByRole('button',{name:'确认撤销',exact:true}).click()
  await page.getByRole('dialog',{name:'二次确认'}).getByRole('button',{name:'确认撤销'}).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText('正式排班部分撤销，待重新校验。')).toBeVisible()
  const cancelled=await get('workspace/')
  expect(cancelled.published_week.status).toBe('partially_cancelled')
  expect(JSON.stringify(cancelled.publications.find(p=>p.id===before.published_week.id).entries)).toBe(original)
  const cancelledDuty=await get(`workspace/?date=${day}&week=${before.published_week.start_date}&shift=A`)
  expect(cancelledDuty.board.source_status).toBe('partially_cancelled')
  expect(cancelledDuty.board.nurses).toHaveLength(0)
  await page.getByRole('button',{name:'查看完整排班'}).click()
  await expect(page.getByText(/本页展示原始发布快照；该版本部分班次已撤销/)).toBeVisible()
  await page.getByRole('button',{name:'返回总览'}).click()
  await page.getByRole('link',{name:'排班管理',exact:true}).click()
  await expect(page.getByText(/本周正式排班部分撤销/)).toBeVisible()
  await page.getByRole('button',{name:'智能生成排班'}).click()
  const generate=page.getByRole('dialog',{name:'智能生成排班'})
  await generate.getByRole('button',{name:'开始生成'}).click()
  await page.getByRole('dialog',{name:'重新生成确认'}).getByRole('button',{name:'确定',exact:true}).click()
  const report=page.getByRole('dialog',{name:'排班校验',exact:true})
  await expect(report).toContainText('生成版本 #')
  await expect(report).toContainText('校验通过')
  await report.getByRole('button',{name:'返回修改'}).click()
  const regenerated=await get('workspace/')
  expect(regenerated.draft.entries.length).toBe(before.draft.entries.length)
  expect(regenerated.draft.generation_version_id).toBeTruthy()
  expect(regenerated.published_week.id).toBe(before.published_week.id)
  await page.getByRole('button',{name:'审核并发布'}).click()
  const publish=page.getByRole('dialog',{name:'审核并发布',exact:true})
  await expect(publish).toContainText('校验通过')
  await publish.getByRole('button',{name:'确认发布'}).click()
  await expect(page.getByRole('dialog',{name:'排班发布成功'})).toBeVisible()
  const after=await get('workspace/')
  expect(after.published_week.id).not.toBe(before.published_week.id)
  expect(after.published_week.status).toBe('published')
  const restoredDuty=await get(`workspace/?date=${day}&week=${before.published_week.start_date}&shift=A`)
  expect(restoredDuty.board.source_publication).toBe(after.published_week.id)
  expect(JSON.stringify(after.publications.find(p=>p.id===before.published_week.id).entries)).toBe(original)
  await page.goto(`/overview/published/${before.published_week.id}`)
  await expect(page.getByText('本页展示历史发布快照，该周期已有更新的正式版本。')).toBeVisible()
})
