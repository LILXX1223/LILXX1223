import { test, expect } from '@playwright/test'

test('床位与当班护士筛选基于同一份数据，桌面布局自适应', async ({ page }) => {
  await page.goto('/')
  await page.getByPlaceholder('请输入账号').fill('group3')
  await page.getByPlaceholder('请输入密码').fill(process.env.E2E_PASSWORD)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '床位分配', exact: true }).click()
  const beds=page.locator('.bed-column')
  const nurses=page.locator('.nurse-column')
  await expect(nurses.locator('.nurse-card').first()).toBeVisible()
  const initialNurses=await nurses.locator('.nurse-card').count()
  expect(initialNurses).toBeGreaterThan(0)
  await beds.getByRole('button', { name: /^空床/ }).click()
  await expect(beds.locator('.bed-card')).toHaveCount(1)
  await expect(beds.locator('.bed-card.empty')).toHaveCount(1)
  await expect(nurses.locator('.nurse-card')).toHaveCount(initialNurses)
  await beds.getByRole('button', { name: /^在床患者/ }).click()
  await expect(beds.locator('.bed-card')).toHaveCount(7)
  await beds.getByRole('button', { name: /^全部床位/ }).click()
  await nurses.getByRole('button', { name: '已分配', exact: true }).click()
  const allocated=await nurses.locator('.nurse-card').count()
  expect(allocated).toBeGreaterThan(0)
  await nurses.getByRole('button', { name: '负荷排序', exact: true }).click()
  await expect(nurses.locator('.nurse-card')).toHaveCount(initialNurses)
  await page.setViewportSize({ width: 1920, height: 1080 })
  expect(await page.locator('.bed-grid').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(3)
  await page.setViewportSize({ width: 1366, height: 768 })
  expect(await page.locator('.bed-grid').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(2)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
